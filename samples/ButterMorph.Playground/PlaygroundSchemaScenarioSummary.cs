/// <summary>
/// Represents a playground schema scenario summary.
/// </summary>
internal sealed class PlaygroundSchemaScenarioSummary
{
    /// <summary>
    /// Gets or sets the context key.
    /// </summary>
    public string ContextKey { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the display name.
    /// </summary>
    public string DisplayName { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the scenario description.
    /// </summary>
    public string Description { get; set; } = string.Empty;

    /// <summary>
    /// Gets or sets the designer path.
    /// </summary>
    public string DesignerPath { get; set; } = string.Empty;
}